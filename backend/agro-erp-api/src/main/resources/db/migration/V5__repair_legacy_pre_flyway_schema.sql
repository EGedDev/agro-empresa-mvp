create index if not exists idx_compras_fecha_compra on compras (fecha_compra);
create index if not exists idx_compra_detalles_compra_id on compra_detalles (compra_id);
create index if not exists idx_compra_detalles_producto_id on compra_detalles (producto_id);
create index if not exists idx_pagos_venta_venta_id on pagos_venta (venta_id);
create index if not exists idx_pagos_venta_fecha_pago on pagos_venta (fecha_pago);
create index if not exists idx_pagos_venta_metodo_pago on pagos_venta (metodo_pago);
create index if not exists idx_pagos_compra_compra_id on pagos_compra (compra_id);
create index if not exists idx_pagos_compra_fecha_pago on pagos_compra (fecha_pago);
create index if not exists idx_pagos_compra_metodo_pago on pagos_compra (metodo_pago);
