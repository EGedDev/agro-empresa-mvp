    alter column saldo_pendiente set not null,
    alter column estado_pago set not null;

create table if not exists proveedores (
    id bigint generated by default as identity primary key,
    nombre varchar(160) not null,
    documento_identidad varchar(20),
    telefono varchar(30),
    email varchar(160),
    direccion varchar(250),
    activo boolean not null default true,
    creado_en timestamp(6) without time zone not null,
    actualizado_en timestamp(6) without time zone not null,
    constraint uk_proveedores_documento_identidad unique (documento_identidad)
);

create table if not exists compras (
    id bigint generated by default as identity primary key,
    proveedor_id bigint not null,
    fecha_compra timestamp(6) without time zone not null,
    estado varchar(30) not null,
    total numeric(12, 2) not null,
    total_pagado numeric(12, 2) not null,
    saldo_pendiente numeric(12, 2) not null,
    estado_pago varchar(30) not null,
    creado_en timestamp(6) without time zone not null,
    actualizado_en timestamp(6) without time zone not null,
    constraint fk_compras_proveedores foreign key (proveedor_id) references proveedores (id),
    constraint chk_compras_estado check (estado in ('REGISTRADA', 'CANCELADA')),
    constraint chk_compras_estado_pago check (estado_pago in ('PENDIENTE', 'PARCIAL', 'PAGADA', 'CANCELADA')),
    constraint chk_compras_total_no_negativo check (total >= 0),
    constraint chk_compras_total_pagado_no_negativo check (total_pagado >= 0),
    constraint chk_compras_saldo_pendiente_no_negativo check (saldo_pendiente >= 0),
    constraint chk_compras_pago_no_supera_total check (total_pagado <= total)
);

create table if not exists compra_detalles (
    id bigint generated by default as identity primary key,
    compra_id bigint not null,
    producto_id bigint not null,
    cantidad integer not null,
    costo_unitario numeric(12, 2) not null,
    subtotal numeric(12, 2) not null,
    constraint fk_compra_detalles_compras foreign key (compra_id) references compras (id),
    constraint fk_compra_detalles_productos foreign key (producto_id) references productos (id),
    constraint chk_compra_detalles_cantidad_positiva check (cantidad > 0),
    constraint chk_compra_detalles_costo_unitario_positivo check (costo_unitario > 0),
    constraint chk_compra_detalles_subtotal_no_negativo check (subtotal >= 0)
);

create table if not exists pagos_venta (
    id bigint generated by default as identity primary key,
    venta_id bigint not null,
    monto numeric(12, 2) not null,
    metodo_pago varchar(40) not null,
    referencia varchar(120),
    fecha_pago timestamp(6) without time zone not null,
    creado_en timestamp(6) without time zone not null,
    constraint fk_pagos_venta_ventas foreign key (venta_id) references ventas (id),
    constraint chk_pagos_venta_monto_positivo check (monto > 0),
    constraint chk_pagos_venta_metodo_pago check (metodo_pago in ('EFECTIVO', 'TRANSFERENCIA', 'YAPE', 'PLIN', 'TARJETA', 'OTRO'))
);

create table if not exists pagos_compra (
    id bigint generated by default as identity primary key,
    compra_id bigint not null,
    monto numeric(12, 2) not null,
    metodo_pago varchar(40) not null,
    referencia varchar(120),
    fecha_pago timestamp(6) without time zone not null,
    creado_en timestamp(6) without time zone not null,
    constraint fk_pagos_compra_compras foreign key (compra_id) references compras (id),
    constraint chk_pagos_compra_monto_positivo check (monto > 0),
    constraint chk_pagos_compra_metodo_pago check (metodo_pago in ('EFECTIVO', 'TRANSFERENCIA', 'YAPE', 'PLIN', 'TARJETA', 'OTRO'))
);

create index if not exists idx_compras_proveedor_id on compras (proveedor_id);
